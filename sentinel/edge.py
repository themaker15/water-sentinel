"""On-device (ESP32) MSPC: model export + a reference detector the firmware copies line by line.

export_model(bundle) -> small JSON-able dict with everything the board needs (no numpy, no sklearn):
    features, mu, P (inverse covariance), thr, med, detector timing, calibration, fault limits.
EdgeDetector is written in plain Python with only + - * / and sorting, exactly the operations the
C firmware will use, so "the laptop simulation behaves like the board" can be tested
(tests check it against the full live scorer).
"""
import json
import math

from .config import MODEL_DIR

EDGE_FILE = "edge_model.json"
STATUS_CODE = {"starting": 0, "normal": 1, "anomaly": 2, "fault": 3}


def export_model(bundle):
    meta = bundle["meta"]
    m = bundle["models"]["mspc"]
    model = m["model"]
    det = meta["detector"]
    return {
        "version": 1, "created": meta.get("created"), "dataset": meta.get("dataset"),
        "features": list(meta["features"]),
        "mu": [float(v) for v in model.mu], "P": [[float(v) for v in row] for row in model.P],
        "sd": [float(v) for v in model.sd],
        "thr": float(m["thr"]), "med": float(m["med"]),
        "median_s": float(det["median_s"]), "ewma_lambda": float(det["ewma_lambda"]),
        "persist_s": float(det["persist_s"]), "release": float(det.get("release", 0.8)),
        "interval_s": float(meta.get("interval_s", 1.0)),
        "calib": {"tds_offset_v": float(meta["calib"]["tds_offset_v"]), "tds_k": float(meta["calib"]["tds_k"]),
                  "ph_points": [[float(a), float(b)] for a, b in meta["calib"]["ph_points"]]},
        "ph_divider": float(meta["ph_divider"]),
        "limits": {k: float(v) for k, v in meta["limits"].items()},
    }


def save_model(edge, out_dir=MODEL_DIR):
    p = out_dir / EDGE_FILE
    p.write_text(json.dumps(edge, indent=1), encoding="utf-8")
    return p


def to_c_header(edge):
    """The same numbers as a C header for the firmware (#include "edge_model.h")."""
    n = len(edge["features"])
    def f(v):                       # a valid C float literal: "3" would become "3f", which does not compile
        t = f"{v:.9g}"
        return (t if any(c in t for c in ".en") else t + ".0") + "f"
    rows = ",\n  ".join("{" + ", ".join(f(v) for v in row) + "}" for row in edge["P"])
    idx = {"temp_c": 0, "tds_ppm": 1, "turb_v": 2, "ph": 3}
    return f"""// Generated by Water Sentinel ({edge.get('created')}). Re-export after every training.
#pragma once
#define EDGE_N {n}
static const int   EDGE_FEAT[EDGE_N] = {{{", ".join(str(idx[x]) for x in edge['features'])}}};  // 0 temp,1 tds,2 turb,3 ph
static const float EDGE_MU[EDGE_N] = {{{", ".join(f(v) for v in edge['mu'])}}};
static const float EDGE_SD[EDGE_N] = {{{", ".join(f(v) for v in edge['sd'])}}};
static const float EDGE_P[EDGE_N][EDGE_N] = {{
  {rows}
}};
static const float EDGE_THR = {f(edge['thr'])}, EDGE_MED = {f(edge['med'])};
static const float EDGE_MEDIAN_S = {f(edge['median_s'])}, EDGE_EWMA_LAMBDA = {f(edge['ewma_lambda'])};
static const float EDGE_PERSIST_S = {f(edge['persist_s'])}, EDGE_RELEASE = {f(edge['release'])};
static const float EDGE_TDS_OFFSET_V = {f(edge['calib']['tds_offset_v'])}, EDGE_TDS_K = {f(edge['calib']['tds_k'])};
static const float EDGE_PH_P1 = {f(edge['calib']['ph_points'][0][0])}, EDGE_PH_V1 = {f(edge['calib']['ph_points'][0][1])};
static const float EDGE_PH_P2 = {f(edge['calib']['ph_points'][1][0])}, EDGE_PH_V2 = {f(edge['calib']['ph_points'][1][1])};
static const float EDGE_PH_DIVIDER = {f(edge['ph_divider'])};
static const float EDGE_TDS_DRY_V = {f(edge['limits']['tds_dry_v'])}, EDGE_ADC_MAX_V = {f(edge['limits']['adc_max_v'])};
static const float EDGE_MIN_SIGNAL_V = {f(edge['limits']['min_signal_v'])};
"""


# ------------------------------------------------------------------ the detector the firmware runs
def tds_ppm(tds_v, temp_c, offset_v, k):
    t = temp_c if temp_c == temp_c else 25.0
    v = max(tds_v - offset_v, 0.0)
    vc = v / (1.0 + 0.02 * (t - 25.0))
    return (133.42 * vc ** 3 - 255.86 * vc ** 2 + 857.39 * vc) * 0.5 * k


def ph_value(pin_v, divider, points):
    (p1, v1), (p2, v2) = points
    if abs(v2 - v1) < 1e-6:
        return float("nan")
    return p1 + (p2 - p1) / (v2 - v1) * (pin_v * divider - v1)


def _bad(v):
    return v is None or v != v


class EdgeDetector:
    """One sample in, one decision out. Same maths as live.Scorer with MSPC."""

    def __init__(self, edge, dt=None):
        self.m = edge
        self.n = len(edge["features"])
        self.set_interval(dt or edge.get("interval_s", 1.0))
        self.reset()

    def set_interval(self, dt):
        dt = min(max(float(dt), 0.05), 30.0)
        win = max(1, int(round(self.m["median_s"] / dt)))
        if win >= 2 and win % 2 == 0:
            win += 1
        self.win = win
        self.persist = max(1, math.ceil(self.m["persist_s"] / dt - 1e-9))
        self.lam = 1.0 - (1.0 - self.m["ewma_lambda"]) ** dt

    def reset(self):
        self.buf = []
        self.e = None
        self.state, self.above, self.below = False, 0, 0

    def fault(self, raw):
        lim, f = self.m["limits"], self.m["features"]
        t, tds, turb, ph = raw.get("temp_c"), raw.get("tds_v"), raw.get("turb_v"), raw.get("ph_pin_v")
        if "temp_c" in f and (_bad(t) or t < -50 or t == 85.0):
            return "temp_missing"
        if "tds_ppm" in f and (_bad(tds) or tds <= lim["tds_dry_v"]):
            return "tds_dry"
        if "tds_ppm" in f and tds >= lim["adc_max_v"]:
            return "tds_saturated"
        if "turb_v" in f and (not _bad(turb)) and turb >= lim["adc_max_v"]:
            return "turb_saturated"
        if "turb_v" in f and (_bad(turb) or turb <= lim["min_signal_v"]):
            return "turb_missing"
        if "ph" in f and (not _bad(ph)) and ph >= lim["adc_max_v"]:
            return "ph_saturated"
        if "ph" in f and (_bad(ph) or ph <= lim["min_signal_v"]):
            return "ph_missing"
        return ""

    def values(self, raw):
        c = self.m["calib"]
        temp = raw.get("temp_c")
        temp = float("nan") if temp is None else float(temp)
        out = {"temp_c": temp, "tds_ppm": tds_ppm(float(raw["tds_v"]), temp, c["tds_offset_v"], c["tds_k"]),
               "turb_v": float(raw["turb_v"])}
        if raw.get("ph_pin_v") is not None:
            out["ph"] = ph_value(float(raw["ph_pin_v"]), self.m["ph_divider"], c["ph_points"])
        return out

    def update(self, raw):
        code = self.fault(raw)
        if code:
            self.buf = []
            return {"status": "fault", "fault": code, "alarm": self.state, "ratio": None}
        v = self.values(raw)
        self.buf.append([v[f] for f in self.m["features"]])
        self.buf = self.buf[-self.win:]
        if len(self.buf) < self.win:
            return {"status": "starting", "alarm": self.state, "ratio": None, "values": v}
        x = [sorted(col)[len(col) // 2] for col in zip(*self.buf)]       # median (window is odd)
        d = [x[i] - self.m["mu"][i] for i in range(self.n)]
        s = sum(d[i] * self.m["P"][i][j] * d[j] for i in range(self.n) for j in range(self.n))
        self.e = s if self.e is None else self.lam * s + (1 - self.lam) * self.e
        ratio = (self.e - self.m["med"]) / (self.m["thr"] - self.m["med"])
        if not self.state:
            self.above = self.above + 1 if ratio > 1.0 else 0
            if self.above >= self.persist:
                self.state, self.below = True, 0
        else:
            self.below = self.below + 1 if ratio < self.m["release"] else 0
            if self.below >= self.persist:
                self.state, self.above = False, 0
        z = [d[i] / self.m["sd"][i] for i in range(self.n)]
        top = max(range(self.n), key=lambda i: abs(z[i]))
        return {"status": "anomaly" if self.state else "normal", "alarm": self.state, "ratio": ratio,
                "values": v, "median": dict(zip(self.m["features"], x)),
                "driver": self.m["features"][top], "driver_z": z[top]}
